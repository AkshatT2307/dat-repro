"""Tables + figures for the 27 Nov additions (per-dataset synthetic models, 2-D field lines).
Reads runs/paperproto/*, writes reports/paperproto/NEW_RESULTS.md and figs/new_*.png. Missing runs show as '—'."""
import json
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / 'runs' / 'paperproto'
REP = ROOT / 'reports' / 'paperproto'; FIGS = REP / 'figs'; FIGS.mkdir(parents=True, exist_ok=True)
SYN = ['m2', 'ot', 'sa']
TESTS = ['m2', 'm2_prestm', 'm2_postm', 'm2_srme', 'ot', 'sa']
NAMES = dict(m2='Marmousi2', m2_prestm='M2 PreSTM', m2_postm='M2 PostSTM', m2_srme='M2 SRME', ot='Overthrust', sa='Salt',
             l2='2D land (NPR-A)', w2='2D marine (NAMSS)', f3='F3', st='Stratton')
JOINT = dict(sg=('C1_idr_sg_s0', 'C2_sup_sg_s0'), sb=('C7_idr_sb_s0', 'C7_sup_sb_s0'), ss=('C8_idr_ss_s0', 'C8_sup_ss_s0'),
             sd=('C9_idr_sd_s0', 'C9_sup_sd_s0'))
LEVELS = dict(sg=(0.5, 1.0), sb=(0.5, 1.0), ss=(0.05, 0.1), sd=(0.3, 0.5))


def load(run, tag='eval'):
    f = RUNS / run / tag / 'summary.json'
    if not f.exists():
        return {}
    return {(r['test'], r['noise'], round(r['level'], 3)): r for r in json.loads(f.read_text())['results']}


def snr(d, test, noise, level, key='snr'):
    r = d.get((test, noise, round(level, 3)))
    return f'{r[key]:.2f}' if r else '—'


def baseline_rows(path):
    f = RUNS / path / 'summary.json'
    out = {}
    if f.exists():
        for r in json.loads(f.read_text())['results']:
            out[(r['method'], r['test'], r['noise'], round(r['level'], 3))] = r
    return out


L = ['# New results (27 Nov 2026): per-dataset synthetic models and 2-D field lines', '',
     'Generated by `kgl/new_tables.py`. Trained on Kaggle T4 GPUs (FP32), protocol P (50k steps, batch 4, 256² crops). '
     'SNR in dB, mean over sections × 3 test-noise seeds. "—" = not available.', '']

# ---------------------------------------------------------------- 1. per-dataset vs joint on own test
L += ['## 1. One model per synthetic dataset vs the joint model (own test set)', '',
      '| Test | noise | σ / p | per-dataset IDR | per-dataset Sup | joint IDR | joint Sup | input SNR |', '|---|---|---|---|---|---|---|---|']
for k in SYN:
    for n in ('sg', 'sb', 'ss', 'sd'):
        pi, ps = load(f'S_{k}_idr_{n}_s0'), load(f'S_{k}_sup_{n}_s0')
        if not pi and not ps and n in ('ss', 'sd'):
            continue
        ji, js = load(JOINT[n][0]), load(JOINT[n][1])
        for lv in LEVELS[n]:
            L.append(f'| {NAMES[k]} | {n} | {lv} | {snr(pi, k, n, lv)} | {snr(ps, k, n, lv)} | {snr(ji, k, n, lv)} | '
                     f'{snr(js, k, n, lv)} | {snr(pi or ji, k, n, lv, "snr_in")} |')
L.append('')

# ---------------------------------------------------------------- 2. transfer matrix
for n in ('sg', 'sb'):
    L += [f'## 2{"ab"[n == "sb"]}. Transfer: train on one dataset, test on all ({n}, σ = 0.5), IDR / Sup', '',
          '| Trained on ↓ / tested on → | ' + ' | '.join(NAMES[t] for t in TESTS) + ' |', '|---|' + '---|' * len(TESTS)]
    for k in SYN:
        pi, ps = load(f'S_{k}_idr_{n}_s0'), load(f'S_{k}_sup_{n}_s0')
        L.append(f'| {NAMES[k]} | ' + ' | '.join(f'{snr(pi, t, n, .5)} / {snr(ps, t, n, .5)}' for t in TESTS) + ' |')
    ji, js = load(JOINT[n][0]), load(JOINT[n][1])
    L.append('| joint (all three) | ' + ' | '.join(f'{snr(ji, t, n, .5)} / {snr(js, t, n, .5)}' for t in TESTS) + ' |')
    L.append('')

# ---------------------------------------------------------------- 3. 2-D field, semi-synthetic
B = baseline_rows('baselines_seis_2d')
L += ['## 3. 2-D field lines, semi-synthetic test (white noise added; original line = reference)', '',
      '| Model | ' + ' | '.join(f'{NAMES[k]} σ{lv}' for k in ('l2', 'w2') for lv in (0.5, 1.0)) + ' |', '|---|' + '---|' * 4]
rows = [('IDR trained on the line (fixed noisy copy)', lambda k: load(f'G_{k}_idrfix_sg'))]
rows += [(f'{lab}, joint synthetic corpus', (lambda r: lambda k: load(r, 'eval_2d'))(r))
         for lab, r in [('IDR', 'C1_idr_sg_s0'), ('Supervised', 'C2_sup_sg_s0')]]
for lab, fn in rows:
    L.append(f'| {lab} | ' + ' | '.join(snr(fn(k), k, 'sg', lv) for k in ('l2', 'w2') for lv in (0.5, 1.0)) + ' |')
for m, lab in [('fx', 'f-x deconvolution'), ('bandpass', 'bandpass 5–60 Hz')]:
    L.append(f'| {lab} | ' + ' | '.join((f"{B[(m, k, 'sg', lv)]['snr']:.2f}" if (m, k, 'sg', lv) in B else '—')
                                       for k in ('l2', 'w2') for lv in (0.5, 1.0)) + ' |')
L.append('| input SNR | ' + ' | '.join((f"{B[('fx', k, 'sg', lv)]['snr_in']:.2f}" if ('fx', k, 'sg', lv) in B else '—')
                                       for k in ('l2', 'w2') for lv in (0.5, 1.0)) + ' |')
L.append('')

# ---------------------------------------------------------------- 4. real noise diagnostics (all four field datasets)
L += ['## 4. Real field noise (no reference): energy removed and signal leakage', '',
      '| Field data | model | % energy removed | % removed in 5–60 Hz | % removed outside band | leakage |LS| |', '|---|---|---|---|---|---|']
for k in ('l2', 'w2', 'f3', 'st'):
    f = RUNS / f'field_{k}' / 'summary.json'
    if not f.exists():
        L.append(f'| {NAMES[k]} | — | — | — | — | — |'); continue
    for name, r in json.loads(f.read_text())['results'].items():
        L.append(f"| {NAMES[k]} | {name} | {100 * r['removed_energy_frac']:.2f} | {100 * r['removed_frac_in_band']:.2f} | "
                 f"{100 * r['removed_frac_out_band']:.2f} | {r['leak_ls']:.3f} |")
L.append('')

# ---------------------------------------------------------------- figures for the 2-D lines
try:
    import matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
    for k in ('l2', 'w2'):
        f = RUNS / f'field_{k}' / 'outputs.npz'
        if not f.exists():
            continue
        z = np.load(f); raw = z['raw'][0]; meta = json.loads((ROOT / 'data/seis' / k / 'meta.json').read_text())
        names = [n for n in z.files if n != 'raw']
        fig, ax = plt.subplots(2, 1 + len(names), figsize=(3.2 * (1 + len(names)), 7), squeeze=False)
        c = np.percentile(np.abs(raw), 98)
        ext = [0, raw.shape[1], raw.shape[0] * meta['dt'], 0]
        ax[0, 0].imshow(raw, cmap='gray', vmin=-c, vmax=c, aspect='auto', interpolation='nearest', extent=ext); ax[0, 0].set_title('raw'); ax[0, 0].set_ylabel('time (s)')
        ax[1, 0].axis('off')
        for i, n in enumerate(names, 1):
            o = z[n][0]
            ax[0, i].imshow(o, cmap='gray', vmin=-c, vmax=c, aspect='auto', interpolation='nearest', extent=ext); ax[0, i].set_title(n)
            ax[1, i].imshow(raw - o, cmap='gray', vmin=-c / 10, vmax=c / 10, aspect='auto', interpolation='nearest', extent=ext); ax[1, i].set_title(f'removed ×10 ({n})')
        fig.suptitle(f'{NAMES[k]}: real-noise application'); fig.tight_layout()
        fig.savefig(FIGS / f'new_field_{k}.png', dpi=110); plt.close(fig)
        L += [f'![{NAMES[k]}](figs/new_field_{k}.png)', '']
        # f-k spectra raw vs IDR-on-line output
        if 'idr_real' in z.files:
            fig, ax = plt.subplots(1, 3, figsize=(12, 3.6))
            for a, (lab, d) in zip(ax, [('raw', raw), ('IDR (trained on line)', z['idr_real'][0]), ('removed', raw - z['idr_real'][0])]):
                F = np.fft.fftshift(np.abs(np.fft.fft2(d)), axes=1)[: d.shape[0] // 2]
                a.imshow(20 * np.log10(F + 1e-6), aspect='auto', interpolation='nearest', cmap='viridis',
                         extent=[-0.5, 0.5, 1 / (2 * meta['dt']), 0]); a.set_title(lab); a.set_xlabel('k (cycles/trace)')
            ax[0].set_ylabel('f (Hz)'); fig.tight_layout(); fig.savefig(FIGS / f'new_fk_{k}.png', dpi=110); plt.close(fig)
            L += [f'![{NAMES[k]} f-k](figs/new_fk_{k}.png)', '']
except Exception as e:   # figures are optional
    L += [f'_figures skipped: {e}_', '']

(REP / 'NEW_RESULTS.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
print('\n'.join(L))
