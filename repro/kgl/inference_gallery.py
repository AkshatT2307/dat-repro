"""Inference figures for every finished Kaggle run (S_*, G_*) and the joint models on the 2-D lines.

For each run: one PNG with a row per (test set, level) stored in eval*/examples.npz
(middle test section, test-noise seed 0): clean | noisy | denoised | removed (noisy − out) | error ×5 (out − clean).
Field runs on real noise: field_<key>/outputs.npz (raw | output | removed ×10) per model.
Writes reports/paperproto/figs/infer/*.png and reports/paperproto/INFERENCE.md.
"""
import json
from pathlib import Path
import numpy as np
import matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / 'runs' / 'paperproto'; REP = ROOT / 'reports' / 'paperproto'
OUT = REP / 'figs' / 'infer'; OUT.mkdir(parents=True, exist_ok=True)
NAMES = dict(m2='Marmousi2', m2_prestm='M2 PreSTM', m2_postm='M2 PostSTM', m2_srme='M2 SRME', ot='Overthrust', sa='Salt',
             l2='2D land (NPR-A)', w2='2D marine (NAMSS)', f3='F3 (3D marine)', st='Stratton (3D land)')


def snr(c, x):
    return 10 * np.log10(np.sum(c ** 2) / max(np.sum((x - c) ** 2), 1e-20))


def dt_of(key):
    for f in (ROOT / 'data/seis' / key / 'meta.json', ROOT / 'data/kratos_drive/x/seis' / key / 'meta.json'):
        if f.exists():
            return json.loads(f.read_text())['dt']
    return 0.004


def gallery(run, tag='eval', title_extra='', out=None):
    out_dir = out or OUT
    f = RUNS / run / tag / 'examples.npz'
    if not f.exists():
        return None
    z = np.load(f); keys = sorted(z.files, key=lambda k: (list(NAMES).index(k.split('__')[0]) if k.split('__')[0] in NAMES else 99, k))
    fig, ax = plt.subplots(len(keys), 5, figsize=(16, 2.9 * len(keys)), squeeze=False)
    for i, k in enumerate(keys):
        test, noise, level = k.split('__')
        clean, noisy, out = z[k].astype(np.float64)
        c = np.percentile(np.abs(clean), 95) * 1.5 or 1.0
        ext = [0, clean.shape[1], clean.shape[0] * dt_of(test), 0]
        cn = 3 * np.std(noisy - clean) or c          # residual panels: scale set by the added noise level
        panels = [('clean', clean, c), (f'noisy {snr(clean, noisy):.2f} dB', noisy, c), (f'denoised {snr(clean, out):.2f} dB', out, c),
                  (f'removed (noisy−out), ±{cn:.2f}', noisy - out, cn), (f'error (out−clean), ±{cn:.2f}', out - clean, cn)]
        for j, (t, a, cc) in enumerate(panels):
            ax[i, j].imshow(a, cmap='gray', vmin=-cc, vmax=cc, aspect='auto', interpolation='nearest', extent=ext)
            ax[i, j].set_title(t, fontsize=8); ax[i, j].tick_params(labelsize=6)
        ax[i, 0].set_ylabel(f'{NAMES.get(test, test)}\n{noise} {level}\ntime (s)', fontsize=8)
    fig.suptitle(f'{run}{title_extra}: inference on held-out test sections (middle section, test seed 0)', fontsize=10)
    fig.tight_layout(rect=(0, 0, 1, 1 - 0.35 / fig.get_figheight())); name = f'{run}{"_" + tag if tag != "eval" else ""}.jpg'
    fig.savefig(out_dir / name, dpi=110, pil_kwargs={'quality': 85}); plt.close(fig)
    return name


def field(key, out=None, max_sections=None):
    out_dir = out or OUT
    f = RUNS / f'field_{key}' / 'outputs.npz'
    if not f.exists():
        return None
    z = np.load(f); names = [n for n in z.files if n != 'raw']; raw = z['raw']
    ns = raw.shape[0] if not max_sections else min(raw.shape[0], max_sections)
    fig, ax = plt.subplots(ns * 2, 1 + len(names), figsize=(3.2 * (1 + len(names)), 5.6 * ns), squeeze=False)
    for s in range(ns):
        r = raw[s].astype(np.float64); c = np.percentile(np.abs(r), 95) * 1.5
        ext = [0, r.shape[1], r.shape[0] * dt_of(key), 0]
        ax[2 * s, 0].imshow(r, cmap='gray', vmin=-c, vmax=c, aspect='auto', interpolation='nearest', extent=ext); ax[2 * s, 0].set_title(f'raw (test section {s})', fontsize=8)
        ax[2 * s + 1, 0].axis('off')
        for j, n in enumerate(names, 1):
            o = z[n][s].astype(np.float64)
            ax[2 * s, j].imshow(o, cmap='gray', vmin=-c, vmax=c, aspect='auto', interpolation='nearest', extent=ext); ax[2 * s, j].set_title(n, fontsize=8)
            e = 100 * np.sum((r - o) ** 2) / np.sum(r ** 2)
            ax[2 * s + 1, j].imshow(r - o, cmap='gray', vmin=-c / 10, vmax=c / 10, aspect='auto', interpolation='nearest', extent=ext)
            ax[2 * s + 1, j].set_title(f'removed ×10 ({e:.2f}% energy)', fontsize=8)
        for a in ax[2 * s:2 * s + 2].ravel():
            a.tick_params(labelsize=6)
    fig.suptitle(f'{NAMES[key]}: models applied to the RAW field data (real noise, no reference)', fontsize=10)
    fig.tight_layout(rect=(0, 0, 1, 1 - 0.35 / fig.get_figheight())); name = f'field_{key}_all_sections.jpg'
    fig.savefig(out_dir / name, dpi=110, pil_kwargs={'quality': 85}); plt.close(fig)
    return name


def main():
    L = ['# Inference gallery: Kaggle runs', '',
         'Generated by `kgl/inference_gallery.py` from the evaluation outputs saved on Kaggle (whole-section inference; outputs '
         'were re-checked locally on CPU, see SANITY.md). Each row: middle held-out test section, test-noise seed 0. '
         'Clean/noisy/denoised share one colour scale (1.5 × 95th percentile of |clean|); removed and error panels use a scale tied to the added noise (printed in each title; same scale as removed).', '']
    runs = sorted(p.name for p in RUNS.iterdir() if p.name.startswith(('S_', 'G_')) and (p / 'training_summary.json').exists())
    L += ['## Per-dataset synthetic models (own test, the other two surveys, Marmousi2 processing variants)', '']
    for r in [x for x in runs if x.startswith('S_')]:
        n = gallery(r)
        if n:
            L += [f'### {r}', '', f'![{r}](figs/infer/{n})', '']
    L += ['## 2-D field lines', '']
    for r in [x for x in runs if x.startswith('G_')]:
        n = gallery(r)
        if n:
            L += [f'### {r} (semi-synthetic: white noise added to the line)', '', f'![{r}](figs/infer/{n})', '']
    for r in ('C1_idr_sg_s0', 'C2_sup_sg_s0', 'C7_idr_sb_s0', 'C7_sup_sb_s0'):
        n = gallery(r, 'eval_2d', ' (joint synthetic corpus)')
        if n:
            L += [f'### {r} on the 2-D lines (joint synthetic model, semi-synthetic test)', '', f'![{r}](figs/infer/{n})', '']
    for k in ('l2', 'w2'):
        n = field(k)
        if n:
            L += [f'### {NAMES[k]}: all models on the raw line (real noise)', '', f'![{k}](figs/infer/{n})', '']
    (REP / 'INFERENCE.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
    print(len(list(OUT.glob('*.jpg'))), 'figures')


if __name__ == '__main__':
    main()
